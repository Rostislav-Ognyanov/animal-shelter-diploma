export function getDefaultSpeciesContent(species) {
  return DEFAULT_SPECIES_CONTENT.find((item) => item.species === species) ?? null;
}

export function mergeSpeciesContentWithDefault(defaultContent, savedContent) {
  if (!savedContent) {
    return defaultContent;
  }

  return {
    ...defaultContent,
    ...savedContent,
    sections: Array.isArray(savedContent.sections) ? savedContent.sections : defaultContent?.sections ?? [],
    issues: Array.isArray(savedContent.issues) ? savedContent.issues : defaultContent?.issues ?? [],
  };
}
