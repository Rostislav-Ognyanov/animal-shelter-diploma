const PAGE_BY_TYPE = {
  privacy: PRIVACY_PAGE,
  terms: TERMS_PAGE,
};

function LegalSection({ section }) {
  return (
    <section className="legal-section">
      <h2>{section.title}</h2>
      {(section.paragraphs ?? []).map((paragraph) => (
        <p key={paragraph}>{paragraph}</p>
      ))}
      {section.items ? (
        <ul>
          {section.items.map((item) => (
            <li key={item}>{item}</li>
          ))}
        </ul>
      ) : null}
      {(section.closing ?? []).map((paragraph) => (
        <p key={paragraph}>{paragraph}</p>
      ))}
    </section>
  );
}

export function LegalPage({ type }) {
  const page = PAGE_BY_TYPE[type] ?? TERMS_PAGE;

  return (
    <main className="route-shell legal-page-shell">
      <section className="legal-page-hero">
        <p>Последна актуализация: {page.updatedAt}</p>
        <h1>{page.title}</h1>
      </section>

      <article className="legal-page-content">
        <div className="legal-intro">
          {page.intro.map((paragraph) => (
            <p key={paragraph}>{paragraph}</p>
          ))}
        </div>

        {page.sections.map((section) => (
          <LegalSection key={section.title} section={section} />
        ))}
      </article>

      <section className="legal-contact-card">
        <h2>Имате въпрос?</h2>
        <p>Свържете се с екипа на приюта, ако имате нужда от уточнение относно тази информация.</p>
        <Link className="about-page-contact-link" to="/svurji-se-s-nas">
          Свържи се с нас
        </Link>
      </section>
    </main>
  );
}
